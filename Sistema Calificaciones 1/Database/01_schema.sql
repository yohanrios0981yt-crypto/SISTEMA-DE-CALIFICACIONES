CREATE TABLE USUARIO (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  NOMBRE VARCHAR2(120 CHAR) NOT NULL,
  CORREO VARCHAR2(160 CHAR) NOT NULL,
  PASSWORD VARCHAR2(100 CHAR) NOT NULL,
  ROL VARCHAR2(20 CHAR) NOT NULL,
  CONSTRAINT UK_USUARIO_CORREO UNIQUE (CORREO),
  CONSTRAINT CK_USUARIO_ROL CHECK (ROL IN ('ESTUDIANTE', 'PROFESOR'))
);

CREATE TABLE ASIGNATURA (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  NOMBRE VARCHAR2(120 CHAR) NOT NULL,
  CODIGO VARCHAR2(20 CHAR) NOT NULL,
  PROFESOR_ID NUMBER NOT NULL,
  CONSTRAINT UK_ASIGNATURA_CODIGO UNIQUE (CODIGO),
  CONSTRAINT FK_ASIG_PROFESOR
    FOREIGN KEY (PROFESOR_ID) REFERENCES USUARIO(ID)
);

CREATE TABLE MATRICULA (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  ESTUDIANTE_ID NUMBER NOT NULL,
  ASIGNATURA_ID NUMBER NOT NULL,
  CONSTRAINT UK_MATRICULA UNIQUE (ESTUDIANTE_ID, ASIGNATURA_ID),
  CONSTRAINT FK_MAT_ESTUDIANTE
    FOREIGN KEY (ESTUDIANTE_ID) REFERENCES USUARIO(ID),
  CONSTRAINT FK_MAT_ASIGNATURA
    FOREIGN KEY (ASIGNATURA_ID) REFERENCES ASIGNATURA(ID)
);

CREATE TABLE CALIFICACION (
  ID NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  MATRICULA_ID NUMBER NOT NULL,
  EVALUACION VARCHAR2(80 CHAR) NOT NULL,
  NOTA NUMBER(4,2) NOT NULL,
  FECHA TIMESTAMP NOT NULL,
  CONSTRAINT CK_NOTA_RANGO CHECK (NOTA BETWEEN 0 AND 5),
  CONSTRAINT FK_NOTA_MATRICULA
    FOREIGN KEY (MATRICULA_ID) REFERENCES MATRICULA(ID)
);

CREATE INDEX IX_MATRICULA_ESTUDIANTE ON MATRICULA(ESTUDIANTE_ID);
CREATE INDEX IX_MATRICULA_ASIGNATURA ON MATRICULA(ASIGNATURA_ID);
CREATE INDEX IX_CALIFICACION_MATRICULA ON CALIFICACION(MATRICULA_ID);


SELECT TABLE_NAME
FROM USER_TABLES
WHERE TABLE_NAME IN ('USUARIO', 'ASIGNATURA', 'MATRICULA', 'CALIFICACION')
ORDER BY TABLE_NAME;